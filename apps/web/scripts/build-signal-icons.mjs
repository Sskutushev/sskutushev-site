import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

/**
 * Lifts the icon outlines out of `simple-icons` into a source file.
 *
 * The package ships one SVG per brand and there are three thousand of them;
 * importing it at runtime to draw eight marks would put the whole catalogue in
 * front of a bundler and hope. The outlines are a few hundred bytes each, so
 * they are generated into source instead and the package stays a dev
 * dependency. Re-run after upgrading it.
 */

/** The stack this profile actually works in, and nothing else. */
const ICONS = [
  ['typescript', 'TypeScript'],
  ['nodedotjs', 'Node.js'],
  ['nestjs', 'NestJS'],
  ['python', 'Python'],
  ['dotnet', '.NET'],
  ['go', 'Go'],
  ['redis', 'Redis'],
  ['react', 'React'],
];

const entries = ICONS.map(([slug, label]) => {
  const source = readFileSync(
    fileURLToPath(new URL(`../node_modules/simple-icons/icons/${slug}.svg`, import.meta.url)),
    'utf8',
  );
  const path = /<path\s+d="([^"]+)"/.exec(source)?.[1];
  if (!path) throw new Error(`No outline found for ${slug}`);
  return { slug, label, path };
});

const file = `/**
 * Brand outlines for the marks that travel out of the System Core.
 *
 * Generated by \`scripts/build-signal-icons.mjs\` from \`simple-icons\`, which is a
 * dev dependency: only these outlines ship. Every viewBox is 24 × 24.
 *
 * They are drawn in a single neutral tone rather than in brand colours. Eight
 * brand palettes at once would put more colour on the object than the whole
 * rest of the page, which the direction spends its budget on avoiding.
 */
export interface SignalIcon {
  slug: string;
  label: string;
  path: string;
}

export const SIGNAL_ICONS: SignalIcon[] = [
${entries.map(({ slug, label, path }) => `  { slug: '${slug}', label: '${label}', path: '${path}' },`).join('\n')}
];
`;

writeFileSync(fileURLToPath(new URL('../src/three/signal-icons.ts', import.meta.url)), file);
console.log(`Signal icons written: ${entries.map(({ label }) => label).join(', ')}.`);
